import sys
import datetime
from fastapi.testclient import TestClient

sys.stdout.reconfigure(encoding='utf-8')

from app.main import app
from app.db.session import SessionLocal
from app.models.entities import (
    User, DailyCheckIn, AIAlert, AIAlertEvidence,
    CareTimelineItem, AuditLog, RoutineBaseline
)

def run_gate_e2e_demonstration():
    print("=" * 65)
    print("EVER NEAR AI — REAL END-TO-END CRITICAL WORKFLOW DEMONSTRATION")
    print("=" * 65)

    client = TestClient(app)
    db = SessionLocal()

    try:
        # STEP 1: Parent Login
        print("\n[Step 1] Parent Login...")
        p_login_res = client.post("/api/auth/login", json={"phone": "9876543210", "password": "1234"})
        assert p_login_res.status_code == 200, f"Parent login failed: {p_login_res.text}"
        p_token = p_login_res.json()["access_token"]
        p_headers = {"Authorization": f"Bearer {p_token}"}
        p_user_id = p_login_res.json()["user_id"]
        print(f"  [OK] Authenticated: {p_login_res.json()['full_name']} (User ID: {p_user_id}, Role: {p_login_res.json()['role']})")

        # STEP 2: Parent Completes Check-In
        print("\n[Step 2] Parent Completes Check-In...")
        today_date = datetime.date.today().isoformat()
        checkin_res = client.post("/api/checkins", json={
            "feeling": "good",
            "feeling_tamil": "நன்றாக உணர்கிறேன்",
            "voice_input": False,
            "note": "Morning tea finished, feeling steady and peaceful"
        }, headers=p_headers)
        assert checkin_res.status_code == 200, f"Check-in failed: {checkin_res.text}"
        print(f"  [OK] Submitted check-in: feeling='{checkin_res.json()['feeling']}' (Tamil: {checkin_res.json()['feeling_tamil']})")

        # STEP 3: Database Stores Check-In (Direct DB Assertion)
        print("\n[Step 3] Verifying Database Storage...")
        db_checkin = db.query(DailyCheckIn).filter(
            DailyCheckIn.user_id == p_user_id,
            DailyCheckIn.check_in_date == today_date
        ).first()
        assert db_checkin is not None, "Check-in not found in database!"
        assert db_checkin.feeling == "good"
        print(f"  [OK] Persisted in database: ID={db_checkin.id}, feeling='{db_checkin.feeling}', date={db_checkin.check_in_date}")

        # STEP 4: Baseline Engine Reads Historical Data
        print("\n[Step 4] Baseline Reads Historical Data...")
        base_res = client.get("/api/ai/baseline", headers=p_headers)
        assert base_res.status_code == 200, f"Baseline failed: {base_res.text}"
        base_data = base_res.json()
        print(f"  [OK] Baseline active: Status='{base_data.get('status')}', Wake='{base_data.get('typical_wake_window')}', Check-in Window='{base_data.get('typical_checkin_window')}'")

        # STEP 5: Family Login
        print("\n[Step 5] Family Login...")
        f_login_res = client.post("/api/auth/login", json={"phone": "9876543211", "password": "1234"})
        assert f_login_res.status_code == 200, f"Family login failed: {f_login_res.text}"
        f_token = f_login_res.json()["access_token"]
        f_headers = {"Authorization": f"Bearer {f_token}"}
        f_user_id = f_login_res.json()["user_id"]
        print(f"  [OK] Family Authenticated: {f_login_res.json()['full_name']} (User ID: {f_user_id}, Role: {f_login_res.json()['role']})")

        # STEP 6: Simulate Abnormal Routine -> Triggers Real Scikit-Learn Isolation Forest
        print("\n[Step 6] Simulating Abnormal Routine & Triggering Scikit-Learn Isolation Forest...")
        sim_res = client.post("/api/ai/simulate-abnormal-routine", json={"scenario": "abnormal_day"}, headers=f_headers)
        assert sim_res.status_code == 200, f"Simulation failed: {sim_res.text}"
        sim_data = sim_res.json()
        alert_id = sim_data["alert_id"]
        change_score = sim_data["change_score"]
        anomaly_score = sim_data["anomaly_score"]
        is_anomaly = sim_data["is_anomaly"]
        print(f"  [OK] Isolation Forest computed: is_anomaly={is_anomaly}, anomaly_score={anomaly_score}, change_score={change_score}")
        print(f"  [OK] Real AIAlert created: ID={alert_id}, Headline='{sim_data['headline']}'")


        # STEP 7: Context Engine Evaluates Signals
        print("\n[Step 7] Context Engine Evaluates Signals...")
        db_evidences = db.query(AIAlertEvidence).filter(AIAlertEvidence.alert_id == alert_id).all()
        assert len(db_evidences) > 0, "No evidence items generated by context engine in database!"
        for ev in db_evidences:
            print(f"  [OK] Signal: {ev.signal_name} -> {ev.signal_status} ({ev.deviation_description})")


        # STEP 8: Family Receives Alert List
        print("\n[Step 8] Family Queries Active AI Alerts...")
        alerts_res = client.get("/api/ai/alerts", headers=f_headers)
        assert alerts_res.status_code == 200
        active_alerts = alerts_res.json()
        matched = next((a for a in active_alerts if a["id"] == alert_id), None)
        assert matched is not None, f"Alert #{alert_id} not visible in family alerts list!"
        assert matched["status"] == "ACTIVE"
        print(f"  [OK] Alert #{alert_id} detected with status={matched['status']}")

        # STEP 9: Family Opens 'Why am I seeing this?' (Explainable AI Breakdown)
        print("\n[Step 9] Family Opens 'Why am I seeing this?' (Explainable AI Breakdown)...")
        expl_res = client.get(f"/api/ai/alerts/{alert_id}/explanation", headers=f_headers)
        assert expl_res.status_code == 200, f"Explanation failed: {expl_res.text}"
        expl_data = expl_res.json()
        print(f"  [OK] Detected Change: {expl_data['detected_change']}")
        print(f"  [OK] Baseline Comparison: {expl_data['baseline_comparison']}")
        print(f"  [OK] System Interpretation: {expl_data['system_interpretation']}")
        print(f"  [OK] Suggested Action: {expl_data['suggested_action']}")
        print(f"  [OK] Disclaimer: {expl_data['disclaimer']}")


        # STEP 10: Family Selects 'Check In'
        print("\n[Step 10] Family Selects 'Check In' Action...")
        checkin_action = client.post(f"/api/ai/alerts/{alert_id}/family-checkin", headers=f_headers)
        assert checkin_action.status_code == 200
        assert checkin_action.json()["status"] == "CHECKED_IN"
        print(f"  [OK] Alert #{alert_id} transitioned to: status='{checkin_action.json()['status']}'")

        # STEP 11: Parent Receives & Responds to Family Prompt
        print("\n[Step 11] Parent Responds to Family Alert...")
        parent_resp = client.post(f"/api/ai/alerts/{alert_id}/parent-respond", headers=p_headers)
        assert parent_resp.status_code == 200
        assert parent_resp.json()["status"] == "RESOLVED"
        print(f"  [OK] Parent confirmed: 'I\\'m okay'. Alert #{alert_id} marked: status='{parent_resp.json()['status']}'")

        # STEP 12: Care Timeline Updates
        print("\n[Step 12] Verifying Care Timeline Updates...")
        timeline_res = client.get("/api/care/timeline", headers=f_headers)
        assert timeline_res.status_code == 200
        timeline_items = timeline_res.json()
        assert len(timeline_items) > 0
        titles = [t["title"] for t in timeline_items[:4]]
        print(f"  [OK] Recent Timeline Events ({len(timeline_items)} total):")
        for t in timeline_items[:3]:
            print(f"       - [{t['event_time']}] ({t['severity']}) {t['title']}: {t['description'][:60]}...")

        # STEP 13: Audit Log Records All Actions
        print("\n[Step 13] Verifying Audit Log Records...")
        audit_res = client.get("/api/audit-logs", headers=f_headers)
        assert audit_res.status_code == 200
        audit_logs = audit_res.json()
        actions = [a["action"] for a in audit_logs[:6]]
        print(f"  [OK] Recent Audit Actions: {actions}")
        assert any("ALERT" in a or "CHECKIN" in a or "AI" in a for a in actions), "Expected AI alert audit logs missing!"

        print("\n" + "=" * 65)
        print(">>> 100% REAL END-TO-END STACK DEMONSTRATION PASSED! <<<")
        print("=" * 65 + "\n")

    finally:
        db.close()

if __name__ == "__main__":
    run_gate_e2e_demonstration()
